"""Generate the MCP tool catalog page and the facts the docs site shows.

Builds the real `paqtra-mcp` and speaks MCP over stdio (initialize +
tools/list), so the published numbers cannot drift from the code. Writes:
  website/docs/reference/mcp-tools.md
  website/src/data/facts.generated.json
CI runs this and fails if either file changes.
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

GROUPS = [
    ("Flows", ("flow",)),
    ("Policies and Cilium", ("polic", "hubble", "cilium")),
    ("Investigate", ("investigat", "connectivity", "rootcause", "healer")),
    ("Anomalies", ("anomal",)),
    ("Security and compliance", ("compliance", "security", "zero")),
    ("eBPF", ("ebpf",)),
    ("Cluster", ("events", "endpoints", "nodes", "dependencies", "heatmap", "health")),
]


def group_of(name):
    key = name.split("_", 1)[1]
    for label, prefixes in GROUPS:
        if key.startswith(prefixes):
            return label
    return "Other"


def mcp_list(binary):
    env = dict(os.environ, PAQTRA_URL="http://127.0.0.1:1")
    msgs = [
        {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {"protocolVersion": "2025-06-18"}},
        {"jsonrpc": "2.0", "method": "notifications/initialized"},
        {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
    ]
    out = subprocess.run(
        [binary], input="\n".join(json.dumps(m) for m in msgs) + "\n",
        capture_output=True, text=True, env=env, timeout=60, check=True,
    ).stdout
    res = {r["id"]: r for r in map(json.loads, out.splitlines()) if "id" in r}
    return res[1]["result"]["serverInfo"], res[2]["result"]["tools"]


def first_sentence(text):
    text = " ".join(text.split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = m.group(1) if m else text
    return s.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def main():
    subprocess.run(["cargo", "build", "--release", "--locked"], cwd=os.path.join(ROOT, "mcp"), check=True)
    info, tools = mcp_list(os.path.join(ROOT, "mcp", "target", "release", "paqtra-mcp"))
    tools = sorted(tools, key=lambda t: t["name"])
    read_only = all(t.get("annotations", {}).get("readOnlyHint") for t in tools)
    if not read_only:
        sys.exit("a paqtra-mcp tool is not marked readOnlyHint; the docs claim read-only")
    server = json.load(open(os.path.join(ROOT, "server.json")))

    groups = {}
    for t in tools:
        groups.setdefault(group_of(t["name"]), []).append(t)
    order = [g for g, _ in GROUPS] + ["Other"]

    lines = [
        "---",
        'title: "MCP tool catalog"',
        "sidebar_position: 2",
        "---",
        "",
        "<!-- GENERATED by scripts/gen-site-facts.py from the paqtra-mcp binary. Do not edit. -->",
        "",
        f"`paqtra-mcp` {info['version']} registers **{len(tools)} tools**, every one of them a read "
        "(`readOnlyHint`) over the Paqtra REST API. There is no write tool. "
        "See [MCP integration](../integrations/mcp-integration.md) for setup.",
        "",
    ]
    for g in order:
        if g not in groups:
            continue
        lines += [f"## {g}", "", "| Tool | What it does |", "|---|---|"]
        for t in groups[g]:
            lines.append(f"| `{t['name']}` | {first_sentence(t.get('description', ''))} |")
        lines.append("")

    ref = os.path.join(ROOT, "website", "docs", "reference")
    os.makedirs(ref, exist_ok=True)
    open(os.path.join(ref, "mcp-tools.md"), "w").write("\n".join(lines))

    docs_md = sum(1 for f in os.listdir(os.path.join(ROOT, "docs")) if f.endswith(".md"))
    facts = {
        "version": server["version"],
        "mcpName": server["name"],
        "mcpImage": server["packages"][0]["identifier"],
        "mcpTools": len(tools),
        "docPages": docs_md,
    }
    os.makedirs(os.path.join(ROOT, "website", "src", "data"), exist_ok=True)
    open(os.path.join(ROOT, "website", "src", "data", "facts.generated.json"), "w").write(
        json.dumps(facts, indent=2) + "\n"
    )
    print("site facts:", json.dumps(facts))


if __name__ == "__main__":
    sys.exit(main())
